#!/usr/bin/env python3
"""Builds the band's pitched instruments in assets/sfz/:

  bass/synth-bass.sfz  a round Afrobeats synth bass: a sine for the body and a filtered saw
                       for the attack, made by sfizz's oscillators (no samples)
  pad/warm-pad.sfz     a soft pad of detuned saws through a low-pass filter (no samples)
  keys/piano.sfz       the Kawai grand of the Versilian Community Sample Library (CC0), one
                       velocity layer over the range the keys play, downloaded into keys/vcsl/

The piano's samples are listed with checksums in keys/samples.json and fetched by
tools/python/fetch_assets.py, like the drum kit's. Run this script only to change the
instruments:

  python tools/python/make_band_kits.py
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

from make_afro_kit import VCSL_COMMIT, VCSL_RAW, fetch, loudest_rms_db

REPO_ROOT = Path(__file__).resolve().parents[2]
SFZ_DIR = REPO_ROOT / "assets" / "sfz"

PIANO_SFZ = "Chordophones/Zithers/Grand Piano, Kawai.sfz"
PIANO_RANGE = (45, 88)    # the notes the keys part can reach after transposition, with room
PIANO_LAYER = "_v3_"      # VCSL's third velocity layer: a full, unforced touch
PIANO_LEVEL_DB = -14.0    # loudest 50 ms of each sample at full velocity
PIANO_SPACING = 4         # at least this many semitones between kept samples (a major third)

HEADER = """// {title}
// Generated by tools/python/make_band_kits.py; edit that script, not this file.
"""

SYNTH_BASS = HEADER.format(title="LiveBand synth bass: sfizz oscillators, no samples (AGPLv3, part of this repository).") + """
<global>
pitch_keycenter=60
ampeg_attack=0.002
ampeg_decay=0.9
ampeg_sustain=55
ampeg_release=0.07
lokey=0
hikey=127

// The body: a pure sine at the note's pitch.
<region>
sample=*sine
volume=-6

// The attack and growl: a saw through a low-pass filter that opens on each note.
<region>
sample=*saw
volume=-17
fil_type=lpf_2p
cutoff=280
resonance=3
fileg_attack=0.001
fileg_decay=0.18
fileg_sustain=15
fileg_depth=2200
"""

WARM_PAD = HEADER.format(title="LiveBand warm pad: sfizz oscillators, no samples (AGPLv3, part of this repository).") + """
<global>
pitch_keycenter=60
ampeg_attack=0.7
ampeg_sustain=100
ampeg_release=1.8
lokey=0
hikey=127

// Five detuned saws, softened by a low-pass filter.
<region>
sample=*saw
oscillator_multi=5
oscillator_detune=16
fil_type=lpf_2p
cutoff=1100
resonance=0.6
volume=-24

// A triangle an octave down for warmth.
<region>
sample=*triangle
transpose=-12
volume=-20
"""


def parse_sfz(text: str) -> list[dict[str, str]]:
    """Regions of a flat SFZ file (VCSL style), with their group's opcodes merged in."""
    regions: list[dict[str, str]] = []
    group: dict[str, str] = {}
    scope = None
    for raw in text.splitlines():
        line = raw.split("//", 1)[0].strip()
        if not line:
            continue
        if line.startswith("<"):
            scope = line
            if line == "<group>":
                group = {}
            elif line == "<region>":
                regions.append(dict(group))
            continue
        key, _, value = line.partition("=")
        if scope == "<group>":
            group[key] = value
        elif scope == "<region>":
            regions[-1][key] = value
    return regions


def tuning_cents(audio: np.ndarray, rate: int, midi: int, offset: int = 0) -> float:
    """How far, in cents, a sample's fundamental is from `midi`: the strongest frequency
    within a quarter tone of it, from 0.1 to 0.6 s after the start."""
    mono = audio[offset:].mean(axis=1)
    segment = mono[int(0.1 * rate):int(0.6 * rate)]
    t = np.arange(len(segment)) / rate
    expected = 440.0 * 2 ** ((midi - 69) / 12)
    cents = np.arange(-50.0, 50.5, 0.5)
    power = [abs(np.sum(segment * np.exp(-2j * np.pi * expected * 2 ** (c / 1200) * t))) for c in cents]
    return float(cents[int(np.argmax(power))])


def build_piano(kit_dir: Path, work: Path) -> tuple[int, float]:
    folder = PIANO_SFZ.rsplit("/", 1)[0]
    regions = [r for r in parse_sfz(fetch(PIANO_SFZ, work / "piano.sfz").read_text())
               if r.get("trigger", "attack") == "attack" and PIANO_LAYER in r["sample"]
               and int(r["hikey"]) >= PIANO_RANGE[0] and int(r["lokey"]) <= PIANO_RANGE[1]]
    regions.sort(key=lambda r: int(r["pitch_keycenter"]))
    if not regions:
        raise ValueError("no piano regions selected")
    # Thin the samples to one every major third or more; sfizz stretches each over its range.
    kept = []
    for r in regions:
        if not kept or int(r["pitch_keycenter"]) - int(kept[-1]["pitch_keycenter"]) >= PIANO_SPACING:
            kept.append(r)
    regions = kept

    manifest = {}
    for r in regions:
        local = f"vcsl/piano/{r['sample'].rsplit('/', 1)[1]}"
        data = fetch(f"{folder}/{r['sample']}", kit_dir / local).read_bytes()
        manifest[local] = {"source": f"{folder}/{r['sample']}", "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
        r["local"] = local

    # Level every sample to the same loudness, so chords sound even across the keyboard, and
    # tune each one to A440 by measuring it: the band's synth bass and pad are exactly in tune.
    for r in regions:
        audio, rate = sf.read(kit_dir / r["local"], always_2d=True)
        offset = int(r.get("offset", 0))
        r["gain"] = PIANO_LEVEL_DB - loudest_rms_db(audio[offset:], rate)
        r["tune"] = -tuning_cents(audio, rate, int(r["pitch_keycenter"]), offset)

    lines = [HEADER.format(title=f"LiveBand piano: Kawai grand from the Versilian Community Sample Library (CC0), commit {VCSL_COMMIT[:12]}."),
             "// One velocity layer; download the samples with tools/python/fetch_assets.py.",
             "", "<control>", "hint_ram_based=1", "", "<global>", "ampeg_attack=0.002", "ampeg_release=0.45", "amp_veltrack=85", ""]
    centres = [int(r["pitch_keycenter"]) for r in regions]
    for i, r in enumerate(regions):
        # Each sample serves the keys nearer to it than to its neighbours.
        lokey = PIANO_RANGE[0] - 12 if i == 0 else (centres[i - 1] + centres[i]) // 2 + 1
        hikey = PIANO_RANGE[1] + 12 if i == len(regions) - 1 else (centres[i] + centres[i + 1]) // 2
        opcodes = [f"lokey={lokey}", f"hikey={hikey}", f"pitch_keycenter={r['pitch_keycenter']}"]
        if round(r["tune"]):
            opcodes.append(f"tune={round(r['tune'])}")
        if r.get("offset"):
            opcodes.append(f"offset={r['offset']}")
        opcodes.append(f"volume={r['gain']:.2f}")
        lines += [f"<region> {' '.join(opcodes)}", f"sample={r['local']}"]
    (kit_dir / "piano.sfz").write_text("\n".join(lines) + "\n")
    (kit_dir / "samples.json").write_text(json.dumps({
        "description": "VCSL samples used by piano.sfz. Downloaded by tools/python/fetch_assets.py.",
        "licence": "CC0 1.0 (Versilian Community Sample Library, https://github.com/sgossner/VCSL)",
        "base_url": VCSL_RAW,
        "files": dict(sorted(manifest.items())),
    }, indent=2) + "\n")
    return len(regions), sum(f["bytes"] for f in manifest.values()) / 1e6


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sfz-dir", type=Path, default=SFZ_DIR)
    args = parser.parse_args()

    for name, text in (("bass/synth-bass.sfz", SYNTH_BASS), ("pad/warm-pad.sfz", WARM_PAD)):
        path = args.sfz_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path}")

    keys = args.sfz_dir / "keys"
    count, megabytes = build_piano(keys, keys / "vcsl" / ".sfz")
    print(f"wrote {keys / 'piano.sfz'}: {count} samples, {megabytes:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
